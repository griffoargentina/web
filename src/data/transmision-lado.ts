/** Lado CAJA/RUEDA de un producto (con override por vehículo para los 14 AMBOS). */
export function getTransmisionLado(
  productCode: string,
  vehicleCode?: string
): TransmisionLado | null {
  const pSide = productSide[productCode];
  if (!pSide) return null;
  if (pSide !== 'AMBOS' || !vehicleCode) return pSide;
  return vehicleSide[productCode]?.[vehicleCode] ?? 'AMBOS';
}

